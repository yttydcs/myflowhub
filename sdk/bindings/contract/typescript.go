package contract

import (
	"bytes"
	"encoding/json"
	"fmt"
	"reflect"
	"sort"
	"strings"

	"github.com/yttydcs/myflowhub/protocol"
)

// VariableTypescript emits wire types directly from the canonical Go structs.
// Named references are queued once so recursive definitions remain recursive
// TypeScript types instead of being expanded into an unbounded schema tree.
func VariableTypescript() ([]byte, error) {
	var output bytes.Buffer
	output.WriteString("// Code generated by mfh-bindgen from canonical Go protocol types. DO NOT EDIT.\n\n")
	output.WriteString("export type JSONValue = null | boolean | number | string | JSONValue[] | { [key: string]: JSONValue };\n\n")
	fmt.Fprintf(&output, "export const SchemaVariableValueV1 = %q;\n", protocol.SchemaVariableValueV1)
	fmt.Fprintf(&output, "export const SchemaVariableWriteV3 = %q;\n\n", protocol.SchemaVariableWriteV3)
	types := make(map[string]reflect.Type)
	var typeName func(reflect.Type) (string, error)
	typeName = func(typ reflect.Type) (string, error) {
		if typ == reflect.TypeOf(json.RawMessage{}) {
			return "JSONValue", nil
		}
		switch typ.Kind() {
		case reflect.Pointer:
			return typeName(typ.Elem())
		case reflect.Struct:
			if typ.Name() == "" {
				return "", fmt.Errorf("anonymous wire struct %s is unsupported", typ)
			}
			if existing, ok := types[typ.Name()]; ok && existing != typ {
				return "", fmt.Errorf("wire type name collision: %s", typ.Name())
			}
			types[typ.Name()] = typ
			return typ.Name(), nil
		case reflect.Slice, reflect.Array:
			element, err := typeName(typ.Elem())
			return element + "[]", err
		case reflect.String:
			return "string", nil
		case reflect.Bool:
			return "boolean", nil
		case reflect.Int, reflect.Int8, reflect.Int16, reflect.Int32, reflect.Int64,
			reflect.Uint, reflect.Uint8, reflect.Uint16, reflect.Uint32, reflect.Uint64,
			reflect.Float32, reflect.Float64:
			return "number", nil
		default:
			return "", fmt.Errorf("unsupported wire type %s", typ)
		}
	}
	for _, root := range []any{protocol.DataSchemaDefinition{}, protocol.VariableValueV1{}, protocol.VariableWriteV3{}} {
		if _, err := typeName(reflect.TypeOf(root)); err != nil {
			return nil, err
		}
	}
	emitted := make(map[string]bool)
	for len(emitted) < len(types) {
		pending := make([]string, 0, len(types)-len(emitted))
		for name := range types {
			if !emitted[name] {
				pending = append(pending, name)
			}
		}
		sort.Strings(pending)
		for _, name := range pending {
			typ := types[name]
			fmt.Fprintf(&output, "export interface %s {\n", name)
			for index := 0; index < typ.NumField(); index++ {
				field := typ.Field(index)
				if !field.IsExported() {
					continue
				}
				tag := strings.Split(field.Tag.Get("json"), ",")
				if tag[0] == "-" {
					continue
				}
				if tag[0] == "" {
					return nil, fmt.Errorf("wire field %s.%s requires a JSON tag", name, field.Name)
				}
				optional := ""
				for _, option := range tag[1:] {
					if option == "omitempty" {
						optional = "?"
					}
				}
				fieldType, err := typeName(field.Type)
				if err != nil {
					return nil, fmt.Errorf("wire field %s.%s: %w", name, field.Name, err)
				}
				fmt.Fprintf(&output, "  %s%s: %s;\n", tag[0], optional, fieldType)
			}
			output.WriteString("}\n\n")
			emitted[name] = true
		}
	}
	return output.Bytes(), nil
}
