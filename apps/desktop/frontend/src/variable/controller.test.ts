import { describe, expect, it, vi } from 'vitest'
import { acquireVariable, MAX_VARIABLE_SESSIONS, VariableController } from './controller'
import { deferred, snapshot, variableAPI, variableResource } from './fixtures.test-support'
import type { VariableValueV1 } from '../generated/variable-contract.generated'

const loaded = (controller: VariableController) => vi.waitFor(() => expect(controller.getSnapshot().snapshot).toBeDefined())
describe('Variable session and CAS', () => {
  it('keeps the SDK durable handle through its 48s renewal and the 60s lease boundary', async () => {
    vi.useFakeTimers()
    const { api, event } = variableAPI()
    const controller = new VariableController(api, 'one', variableResource())
    try {
      controller.start(); event(snapshot(), 'snapshot'); await vi.advanceTimersByTimeAsync(0)
      controller.edit(true)
      setTimeout(() => event(snapshot(false, '9007199254740994'), 'snapshot'), 48_000)
      await vi.advanceTimersByTimeAsync(60_001)
      expect(controller.getSnapshot().live).toBe(true)
      expect(controller.getSnapshot().base?.revision).toBe('9007199254740994')
      expect(controller.getSnapshot().draft).toBe(true)
      expect(api.subscribe).toHaveBeenCalledTimes(1)
      expect(api.cancel).not.toHaveBeenCalled()
    } finally { controller.stop(); vi.useRealTimers() }
  })
  it.each(['gap', 'expired'] as const)('keeps polling after %s and resumes only with a full snapshot', async (kind) => {
    const { api, event, push } = variableAPI()
    const resource = variableResource()
    const controller = new VariableController(api, 'one', resource)
    controller.start(); event(snapshot(), 'snapshot'); await vi.waitFor(() => expect(controller.getSnapshot().live).toBe(true))
    controller.edit(true)
    push({ kind: 'event', payload: { kind, owner_node_id: resource.id.owner_node_id, resource_name: resource.id.name, reason: 'lease_expired' } })
    await vi.waitFor(() => expect(controller.getSnapshot().live).toBe(false))
    expect(api.cancel).not.toHaveBeenCalled()
    await controller.apply(); expect(api.operate).not.toHaveBeenCalled()
    event(snapshot(false, '9007199254740994'), 'snapshot')
    await vi.waitFor(() => expect(controller.getSnapshot().live).toBe(true))
    expect(controller.getSnapshot().blocked).toBe('')
    expect(controller.getSnapshot().draft).toBe(true)
    expect(api.subscribe).toHaveBeenCalledTimes(1)
    controller.stop()
  })
  it('restarts a terminated subscription on explicit refresh after reauthorization without retry loops', async () => {
    const { api, event } = variableAPI()
    vi.mocked(api.subscribe).mockRejectedValueOnce(new Error('Forbidden: subscribe'))
    const controller = new VariableController(api, 'one', variableResource())
    controller.start(); await vi.waitFor(() => expect(controller.getSnapshot().observation).toContain('Forbidden'))
    await Promise.resolve(); expect(api.subscribe).toHaveBeenCalledTimes(1)
    await controller.refresh(); event(snapshot(), 'snapshot')
    await vi.waitFor(() => expect(controller.getSnapshot().live).toBe(true))
    expect(api.subscribe).toHaveBeenCalledTimes(2)
    controller.stop()
  })
  it('reads the exact revision without requiring subscribe permission', async () => {
    const { api } = variableAPI()
    vi.mocked(api.subscribe).mockRejectedValue(new Error('Forbidden: subscribe'))
    const controller = new VariableController(api, 'personal', variableResource())
    controller.start(); await loaded(controller)
    await vi.waitFor(() => expect(controller.getSnapshot().observation).toContain('Forbidden'))
    expect(controller.getSnapshot().live).toBe(false)
    controller.edit(true); await controller.apply()
    expect(api.operate).toHaveBeenCalledWith('719', 'unregistered/8f7ad/value', 'write', 'mfh.variable-write.v3', { version: 3, expected_instance_id: 'a'.repeat(32), expected_revision: '9007199254740993', value: true })
    expect(controller.getSnapshot().snapshot?.value).toBe(false)
    controller.stop()
  })
  it('keeps drafts on metadata updates, advances CAS, and conflicts on real value changes', async () => {
    const { api, event } = variableAPI()
    const controller = new VariableController(api, 'personal', variableResource())
    controller.start(); event(snapshot(), 'snapshot'); await loaded(controller)
    controller.edit(true)
    event({ ...snapshot(false, '9007199254740994'), status: 'stale', observed_at_unix_ms: 101 })
    await vi.waitFor(() => expect(controller.getSnapshot().base?.revision).toBe('9007199254740994'))
    expect(controller.getSnapshot().draft).toBe(true)
    event(snapshot(true, '9007199254740995'))
    await vi.waitFor(() => expect(controller.getSnapshot().conflict).toBe(true))
    expect(controller.getSnapshot().base?.revision).toBe('9007199254740994')
    event(snapshot(false, '9007199254740996'))
    await vi.waitFor(() => expect(controller.getSnapshot().snapshot?.revision).toBe('9007199254740996'))
    expect(controller.getSnapshot().conflict).toBe(true)
    expect(controller.getSnapshot().base?.revision).toBe('9007199254740994')
    await controller.apply(); expect(api.operate).not.toHaveBeenCalled()
    controller.stop(); await vi.waitFor(() => expect(api.cancel).toHaveBeenCalledTimes(1))
  })
  it('ignores a late read and out-of-order events', async () => {
    const read = deferred<VariableValueV1>()
    const { api, event } = variableAPI()
    vi.mocked(api.snapshot).mockReturnValueOnce(read.promise)
    const controller = new VariableController(api, 'one', variableResource())
    controller.start(); event(snapshot(true, '12'), 'snapshot'); await loaded(controller)
    read.resolve(snapshot(false, '10')); await vi.waitFor(() => expect(controller.getSnapshot().loading).toBe(false))
    event(snapshot(false, '11')); await Promise.resolve()
    expect(controller.getSnapshot().snapshot?.revision).toBe('12')
    expect(controller.getSnapshot().snapshot?.value).toBe(true)
    controller.stop()
  })
  it('blocks a draft after unavailable, recovery and resource recreation until reset', async () => {
    const { api, event } = variableAPI()
    const controller = new VariableController(api, 'one', variableResource())
    controller.start(); event(snapshot(), 'snapshot'); await loaded(controller); controller.edit(true)
    const missing = { ...snapshot(false, '9007199254740994'), status: 'unavailable' }; delete missing.value
    event(missing); await vi.waitFor(() => expect(controller.getSnapshot().blocked).toContain('不可用'))
    event(snapshot(false, '9007199254740995')); await vi.waitFor(() => expect(controller.getSnapshot().blocked).toContain('失效'))
    await controller.apply(); expect(api.operate).not.toHaveBeenCalled()
    controller.reset(); controller.edit(true)
    event(snapshot(false, '1', { type: 'boolean' }, 'b'.repeat(32)), 'snapshot')
    await vi.waitFor(() => expect(controller.sessionKey).toContain('b'.repeat(32)))
    await controller.apply(); expect(api.operate).not.toHaveBeenCalled()
    expect(controller.getSnapshot().blocked).toContain('重建')
    controller.reset(); expect(controller.getSnapshot().base?.instance_id).toBe('b'.repeat(32))
    controller.stop()
  })
  it('never replaces a rebuilt instance with a late successful write', async () => {
    const write = deferred<Awaited<ReturnType<ReturnType<typeof variableAPI>['api']['operate']>>>()
    const { api, event } = variableAPI()
    vi.mocked(api.operate).mockReturnValue(write.promise)
    const controller = new VariableController(api, 'one', variableResource())
    controller.start(); event(snapshot(), 'snapshot'); await loaded(controller); controller.edit(true)
    const applying = controller.apply()
    event(snapshot(false, '1', { type: 'boolean' }, 'b'.repeat(32)), 'snapshot')
    await vi.waitFor(() => expect(controller.getSnapshot().snapshot?.revision).toBe('1'))
    write.resolve({ schema: 'mfh.variable-value.v1', payload: snapshot(true, '9007199254740994') }); await applying
    expect(controller.getSnapshot().snapshot?.instance_id).toBe('b'.repeat(32))
    expect(controller.getSnapshot().snapshot?.value).toBe(false)
    controller.stop()
  })
  it('makes revocation visible and Reset cannot bypass a required read', async () => {
    const { api, event, push } = variableAPI()
    const controller = new VariableController(api, 'one', variableResource())
    controller.start(); event(snapshot(), 'snapshot'); await vi.waitFor(() => expect(controller.getSnapshot().live).toBe(true))
    controller.edit(true); push({ kind: 'error', payload: { code: 'Forbidden', message: 'read revoked' } })
    await vi.waitFor(() => expect(controller.getSnapshot().live).toBe(false))
    expect(controller.getSnapshot().observation).toContain('Forbidden')
    controller.reset(); controller.edit(true); await controller.apply()
    expect(api.operate).not.toHaveBeenCalled()
    controller.stop()
  })
  it('preserves draft on rejected writes and never advertises an unconfirmed request value', async () => {
    const { api } = variableAPI()
    vi.mocked(api.operate).mockRejectedValue(new Error('Forbidden: write'))
    const controller = new VariableController(api, 'one', variableResource(false))
    controller.start(); await loaded(controller); controller.edit(true); await controller.apply()
    expect(controller.getSnapshot()).toMatchObject({ dirty: true, draft: true, writing: false })
    expect(controller.getSnapshot().snapshot?.value).toBe(false)
    expect(controller.getSnapshot().error).toContain('Forbidden')
    controller.stop()
  })
  it('cancels an in-flight subscription when its last consumer unmounts', async () => {
    const subscription = deferred<number>()
    const { api } = variableAPI()
    vi.mocked(api.subscribe).mockReturnValue(subscription.promise)
    const acquired = acquireVariable(api, 'profile', variableResource())
    acquired.release(); subscription.resolve(99)
    await vi.waitFor(() => expect(api.cancel).toHaveBeenCalledExactlyOnceWith(99))
    expect(acquired.controller.getSnapshot().snapshot).toBeUndefined()
  })
  it('shares Inspector/View sessions, isolates Profiles and bounds then frees the cache', async () => {
    const { api } = variableAPI()
    const resource = variableResource(false, false)
    const a = acquireVariable(api, 'one', resource), b = acquireVariable(api, 'one', resource), c = acquireVariable(api, 'two', resource)
    expect(a.controller).toBe(b.controller); expect(c.controller).not.toBe(a.controller)
    a.release(); expect(b.controller.getSnapshot().blocked).not.toBe('会话已释放')
    b.release(); c.release()
    const sessions = Array.from({ length: MAX_VARIABLE_SESSIONS }, (_, index) => acquireVariable(api, String(index), resource))
    expect(() => acquireVariable(api, 'overflow', resource)).toThrow('最多')
    sessions.forEach((session) => session.release())
    const again = acquireVariable(api, 'new', resource); again.release()
  })
  it('rejects unknown versions before I/O', () => {
    const { api } = variableAPI(); const resource = { ...variableResource(), type_version: 99 }
    const controller = new VariableController(api, 'one', resource); controller.start()
    expect(controller.getSnapshot().blocked).toContain('unsupported'); expect(api.snapshot).not.toHaveBeenCalled(); expect(api.subscribe).not.toHaveBeenCalled(); controller.stop()
  })
})
