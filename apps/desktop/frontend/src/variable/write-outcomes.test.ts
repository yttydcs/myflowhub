import { afterEach, describe, expect, it, vi } from 'vitest'
import { VariableController } from './controller'
import { deferred, snapshot, variableAPI, variableResource } from './fixtures.test-support'

afterEach(() => vi.useRealTimers())
const load = async (controller: VariableController) => {
  controller.start()
  await vi.waitFor(() => expect(controller.getSnapshot().snapshot).toBeDefined())
  controller.edit(true)
}

describe('bounded write outcomes', () => {
  it('preserves the legacy signed-zero base boundary instead of stringifying it for native preflight', async () => {
    const initial = snapshot(-0, '9007199254740993', { type: 'number' })
    const { api } = variableAPI(initial)
    api.writeVariableFromSnapshot = vi.fn()
    const controller = new VariableController(api, 'p', variableResource(false))
    controller.start()
    await vi.waitFor(() => expect(controller.getSnapshot().snapshot).toBeDefined())
    controller.edit(1)
    const actual = snapshot(1, '9007199254740994', { type: 'number' })
    vi.mocked(api.snapshot).mockResolvedValueOnce(initial).mockResolvedValue(actual)
    vi.mocked(api.operate).mockResolvedValue({ schema: 'mfh.variable-value.v1', payload: actual })
    await controller.apply()
    expect(api.writeVariableFromSnapshot).not.toHaveBeenCalled()
    expect(api.operate).toHaveBeenCalledTimes(1)
    expect(controller.getSnapshot().writeOutcome).toBe('confirmed')
    controller.stop()
  })
  it('uses the native single-dispatch path and still requires an independent fresh read', async () => {
    const { api } = variableAPI()
    const controller = new VariableController(api, 'p', variableResource(false))
    await load(controller)
    const actual = snapshot(true, '9007199254740999')
    api.writeVariableFromSnapshot = vi.fn().mockResolvedValue({ sent: true, expected_revision: '9007199254740998', response_json: JSON.stringify({ schema: 'mfh.variable-value.v1', payload: actual }) })
    vi.mocked(api.snapshot).mockResolvedValue(actual)
    await controller.apply()
    expect(api.writeVariableFromSnapshot).toHaveBeenCalledTimes(1)
    expect(api.operate).not.toHaveBeenCalled()
    expect(api.snapshot).toHaveBeenCalledTimes(2)
    expect(controller.getSnapshot()).toMatchObject({ writeOutcome: 'confirmed', dirty: false, draft: true })
    controller.stop()
  })
  it.each([
    { sent: false, error: 'read disconnected', outcome: 'rejected' },
    { sent: true, error: 'conflict: sampling advanced', outcome: 'rejected' },
    { sent: true, error: 'connection lost after dispatch', outcome: 'uncertain' },
  ])('preserves the native dispatch boundary: $error', async ({ sent, error, outcome }) => {
    const { api } = variableAPI()
    const controller = new VariableController(api, 'p', variableResource(false))
    await load(controller)
    api.writeVariableFromSnapshot = vi.fn().mockResolvedValue({ sent, error })
    await controller.apply()
    expect(controller.getSnapshot()).toMatchObject({ writeOutcome: outcome, dirty: true, draft: true, writing: false })
    expect(api.writeVariableFromSnapshot).toHaveBeenCalledTimes(1)
    expect(api.operate).not.toHaveBeenCalled()
    expect(api.snapshot).toHaveBeenCalledTimes(1)
    controller.stop()
  })
  it('does not turn a native acknowledgement into a confirmed UI state when readback fails', async () => {
    const { api } = variableAPI()
    const controller = new VariableController(api, 'p', variableResource(false))
    await load(controller)
    api.writeVariableFromSnapshot = vi.fn().mockResolvedValue({ sent: true, expected_revision: '9007199254740993', response_json: JSON.stringify({ schema: 'mfh.variable-value.v1', payload: snapshot(true, '9007199254740994') }) })
    vi.mocked(api.snapshot).mockRejectedValue(new Error('read disconnected'))
    await controller.apply()
    expect(controller.getSnapshot()).toMatchObject({ writeOutcome: 'confirmed-unreadable', dirty: true, draft: true })
    expect(api.writeVariableFromSnapshot).toHaveBeenCalledTimes(1)
    controller.stop()
  })
  it('times out a missing native reply without replaying a write or accepting its late acknowledgement', async () => {
    vi.useFakeTimers()
    const { api } = variableAPI()
    const reply = deferred<{ sent: boolean; expected_revision: string; response_json: string }>()
    api.writeVariableFromSnapshot = vi.fn().mockReturnValue(reply.promise)
    const controller = new VariableController(api, 'p', variableResource(false))
    controller.start(); await vi.advanceTimersByTimeAsync(0); controller.edit(true)
    const applying = controller.apply()
    await vi.advanceTimersByTimeAsync(5000); await applying
    expect(controller.getSnapshot()).toMatchObject({ writeOutcome: 'uncertain', dirty: true, draft: true, writing: false })
    reply.resolve({ sent: true, expected_revision: '9007199254740993', response_json: JSON.stringify({ schema: 'mfh.variable-value.v1', payload: snapshot(true, '9007199254740994') }) })
    await vi.advanceTimersByTimeAsync(0)
    expect(api.snapshot).toHaveBeenCalledTimes(1)
    expect(controller.getSnapshot().snapshot?.value).toBe(false)
    await controller.apply()
    expect(api.writeVariableFromSnapshot).toHaveBeenCalledTimes(1)
    controller.stop()
  })
  it('ends at five seconds, preserves intent and ignores late acknowledgements without a retry or read', async () => {
    vi.useFakeTimers()
    const { api } = variableAPI()
    const reply = deferred<Awaited<ReturnType<typeof api.operate>>>()
    vi.mocked(api.operate).mockReturnValue(reply.promise)
    const controller = new VariableController(api, 'p', variableResource(false))
    controller.start(); await vi.advanceTimersByTimeAsync(0); controller.edit(true)
    const applying = controller.apply()
    await vi.advanceTimersByTimeAsync(4999)
    expect(controller.getSnapshot().writing).toBe(true)
    await vi.advanceTimersByTimeAsync(1); await applying
    expect(controller.getSnapshot()).toMatchObject({ writing: false, dirty: true, draft: true, writeOutcome: 'uncertain' })
    expect(controller.getSnapshot().blocked).toContain('结果不确定')
    reply.resolve({ schema: 'mfh.variable-value.v1', payload: snapshot(true, '9007199254740994') })
    await vi.advanceTimersByTimeAsync(0)
    expect(api.operate).toHaveBeenCalledTimes(1)
    expect(api.snapshot).toHaveBeenCalledTimes(2)
    expect(controller.getSnapshot().snapshot?.value).toBe(false)
    await controller.apply(); expect(api.operate).toHaveBeenCalledTimes(1)
    controller.stop()
  })
  it('reports acknowledged writes separately when the independent read fails', async () => {
    const { api } = variableAPI()
    const controller = new VariableController(api, 'p', variableResource(false))
    await load(controller)
    vi.mocked(api.operate).mockResolvedValue({ schema: 'mfh.variable-value.v1', payload: snapshot(true, '9007199254740994') })
    vi.mocked(api.snapshot).mockResolvedValueOnce(snapshot()).mockRejectedValue(new Error('read disconnected'))
    await controller.apply()
    expect(controller.getSnapshot()).toMatchObject({ writeOutcome: 'confirmed-unreadable', dirty: true, draft: true, writing: false, conflict: false })
    expect(controller.getSnapshot().error).toContain('写入已确认，回读失败')
    expect(api.operate).toHaveBeenCalledTimes(1)
    vi.mocked(api.snapshot).mockResolvedValue(snapshot(true, '9007199254740994'))
    await controller.refresh()
    expect(controller.getSnapshot()).toMatchObject({ writeOutcome: 'confirmed', dirty: false, writing: false, conflict: false })
    expect(api.operate).toHaveBeenCalledTimes(1)
    controller.stop()
  })
  it('requires a fresh read at or after the acknowledged revision for success', async () => {
    const { api } = variableAPI()
    const controller = new VariableController(api, 'p', variableResource(false))
    await load(controller)
    const actual = snapshot(true, '9007199254740994')
    vi.mocked(api.operate).mockResolvedValue({ schema: 'mfh.variable-value.v1', payload: actual })
    vi.mocked(api.snapshot).mockResolvedValueOnce(snapshot()).mockResolvedValue(actual)
    await controller.apply()
    expect(controller.getSnapshot()).toMatchObject({ writeOutcome: 'confirmed', dirty: false, writing: false })
    expect(api.snapshot).toHaveBeenCalledTimes(3)
    expect(controller.getSnapshot().snapshot).toEqual(actual)
    controller.stop()
  })
  it('preserves drafts on an explicit permission rejection', async () => {
    const { api } = variableAPI()
    const controller = new VariableController(api, 'p', variableResource(false))
    await load(controller)
    vi.mocked(api.operate).mockRejectedValue(new Error('Forbidden: write'))
    await controller.apply()
    expect(controller.getSnapshot()).toMatchObject({ writeOutcome: 'rejected', dirty: true, draft: true, writing: false })
    expect(api.snapshot).toHaveBeenCalledTimes(2)
    controller.stop()
  })
  it('uses a fresh metadata revision for one write while preserving the original value boundary', async () => {
    const { api } = variableAPI()
    const controller = new VariableController(api, 'p', variableResource(false))
    await load(controller)
    vi.mocked(api.snapshot).mockResolvedValueOnce(snapshot(false, '9007199254740998')).mockResolvedValue(snapshot(true, '9007199254740999'))
    vi.mocked(api.operate).mockResolvedValue({ schema: 'mfh.variable-value.v1', payload: snapshot(true, '9007199254740999') })
    await controller.apply()
    expect(api.operate).toHaveBeenCalledExactlyOnceWith('719', 'unregistered/8f7ad/value', 'write', 'mfh.variable-write.v3', {
      version: 3, expected_instance_id: 'a'.repeat(32), expected_revision: '9007199254740998', value: true,
    })
    expect(controller.getSnapshot().writeOutcome).toBe('confirmed')
    controller.stop()
  })
  it('rejects a changed actual value before dispatch and preserves the draft', async () => {
    const { api } = variableAPI()
    const controller = new VariableController(api, 'p', variableResource(false))
    await load(controller)
    vi.mocked(api.snapshot).mockResolvedValue(snapshot(true, '9007199254740994'))
    await controller.apply()
    expect(api.operate).not.toHaveBeenCalled()
    expect(controller.getSnapshot()).toMatchObject({ writeOutcome: 'rejected', dirty: true, draft: true, conflict: true })
    controller.stop()
  })
  it('does not dispatch after a preflight read exceeds the shared deadline', async () => {
    vi.useFakeTimers()
    const { api } = variableAPI()
    const controller = new VariableController(api, 'p', variableResource(false))
    controller.start(); await vi.advanceTimersByTimeAsync(0); controller.edit(true)
    const read = deferred<ReturnType<typeof snapshot>>()
    vi.mocked(api.snapshot).mockReturnValue(read.promise)
    const applying = controller.apply()
    await vi.advanceTimersByTimeAsync(5000); await applying
    read.resolve(snapshot()); await vi.advanceTimersByTimeAsync(0)
    expect(api.operate).not.toHaveBeenCalled()
    expect(controller.getSnapshot()).toMatchObject({ writeOutcome: 'rejected', dirty: true, writing: false })
    controller.stop()
  })
  it('requires an acknowledgement beyond the actual preflight revision', async () => {
    const { api } = variableAPI()
    const controller = new VariableController(api, 'p', variableResource(false))
    await load(controller)
    vi.mocked(api.snapshot).mockResolvedValue(snapshot(false, '9007199254740998'))
    vi.mocked(api.operate).mockResolvedValue({ schema: 'mfh.variable-value.v1', payload: snapshot(true, '9007199254740994') })
    await controller.apply()
    expect(controller.getSnapshot()).toMatchObject({ writeOutcome: 'uncertain', dirty: true, writing: false })
    expect(api.snapshot).toHaveBeenCalledTimes(2)
    controller.stop()
  })
  it('ends a preflight instance replacement without dispatching the old draft', async () => {
    const { api } = variableAPI()
    const controller = new VariableController(api, 'p', variableResource(false))
    await load(controller)
    vi.mocked(api.snapshot).mockResolvedValue(snapshot(false, '1', { type: 'boolean' }, 'b'.repeat(32)))
    await controller.apply()
    expect(api.operate).not.toHaveBeenCalled()
    expect(controller.getSnapshot()).toMatchObject({ writeOutcome: 'rejected', dirty: true, writing: false })
    expect(controller.getSnapshot().blocked).toContain('重建')
    controller.stop()
  })
})
