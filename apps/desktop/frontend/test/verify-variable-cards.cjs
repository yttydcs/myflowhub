// Run against `npm run dev -- --host 127.0.0.1 --port 62817`.
// PLAYWRIGHT_PATH may point to an existing Playwright installation (no runtime dependency).
const { chromium } = require(process.env.PLAYWRIGHT_PATH || 'playwright');
const assert = require('node:assert/strict');
const path = require('node:path');
(async () => {
  const browser = await chromium.launch({ channel: 'msedge', headless: true });
  const page = await browser.newPage({ viewport: { width: 1264, height: 781 } });
  const errors = [];
  page.on('pageerror', error => errors.push(error.message));
  page.on('dialog', dialog => dialog.accept());
  const artifact = name => path.join(process.env.QA_ARTIFACTS || process.cwd(), `variable-cards-${name}.png`);
  const drag = async (source, target, { cancel = false } = {}) => {
    await source.scrollIntoViewIfNeeded();
    const bounds = await source.boundingBox(); assert.ok(bounds, 'source visible');
    await page.mouse.move(bounds.x + bounds.width / 2, bounds.y + bounds.height / 2);
    await page.mouse.down();
    await page.mouse.move(bounds.x + bounds.width / 2 + 10, bounds.y + bounds.height / 2, { steps: 3 });
    await page.mouse.move(target.x, target.y, { steps: 20 });
    await page.waitForTimeout(180);
    if (cancel) await page.keyboard.press('Escape');
    await page.mouse.up();
    await page.waitForTimeout(200);
  };
  const point = async (locator, x = .5, y = .5) => { const b = await locator.boundingBox(); assert.ok(b); return { x: b.x + b.width * x, y: b.y + b.height * y }; };
  const catalog = name => page.getByRole('treeitem', { name: `${name} metrics/${name}`, exact: true });
  const cpu = page.locator('#workspace-pane-cpu_percent');
  const memory = page.locator('#workspace-pane-memory_percent');
  const row = (card, name) => card.locator('.variable-list-row').filter({ has: page.getByRole('heading', { name, exact: true }) });
  try {
    await page.goto(`${process.env.QA_URL || 'http://127.0.0.1:62817'}/test/variable-cards.html`, { waitUntil: 'networkidle' });
    await catalog('battery_percent').waitFor();
    assert.equal(await page.locator('.widget').count(), 2);
    assert.equal(await page.locator('.widget-drag-handle').count(), 0);
    await drag(catalog('battery_percent'), await point(cpu.locator('.widget-body')), { cancel: true });
    assert.equal(await page.getByRole('button', { name: '编辑视图', exact: true }).count(), 1, 'cancelled drag stays viewing');
    await drag(catalog('battery_percent'), { x: 12, y: 12 });
    assert.equal(await page.locator('.widget-drag-handle').count(), 0, 'invalid drop stays viewing');
    await drag(catalog('battery_percent'), await point(cpu.locator('.widget-body')));
    assert.equal(await cpu.locator('.variable-list-row').count(), 2, 'single converts on catalog drop');
    assert.equal(await page.getByRole('button', { name: '保存视图', exact: true }).count(), 1, 'valid drop enters editing');
    await drag(catalog('battery_charging'), await point(cpu.locator('.variable-list-add')));
    assert.equal(await cpu.locator('.variable-list-row').count(), 3);
    await drag(catalog('battery_percent'), await point(cpu.locator('.variable-list-add')));
    assert.equal(await cpu.locator('.variable-list-row').count(), 3, 'duplicate does not insert');
    assert.ok((await page.getByRole('alert').allTextContents()).some(text => text.includes('已包含')));
    await page.getByRole('button', { name: '关闭错误消息' }).click();
    await drag(memory.getByRole('button', { name: '拖动变量 memory_percent', exact: true }), await point(cpu.locator('.variable-list-add')));
    assert.equal(await cpu.locator('.variable-list-row').count(), 4, 'single variable can move into group');
    assert.equal(await memory.locator('.variable-list-row').count(), 0, 'empty source retained');
    await drag(row(cpu, 'memory_percent').getByRole('button', { name: '拖动变量 memory_percent' }), await point(row(cpu, 'cpu_percent'), .5, .15));
    assert.equal(await cpu.locator('.variable-list-row .variable-title').first().innerText(), 'memory_percent', 'group rows reorder');
    await drag(row(cpu, 'battery_charging').getByRole('button', { name: '拖动变量 battery_charging' }), await point(memory.locator('.widget-body')));
    assert.equal(await memory.locator('.variable-list-row').count(), 1, 'cross-group movement');
    await drag(catalog('brightness_percent'), await point(cpu.locator('.variable-list-add')));
    const brightness = row(cpu, 'brightness_percent');
    const numeric = brightness.getByRole('spinbutton');
    await numeric.fill('');
    await numeric.evaluate(element => { window.__qaInput = element });
    await drag(brightness.getByRole('button', { name: '拖动变量 brightness_percent' }), await point(memory.locator('.variable-list-add')));
    assert.equal(await row(memory, 'brightness_percent').getByRole('spinbutton').evaluate(element => element === window.__qaInput), true, 'moving keeps DOM input');
    assert.equal(await row(memory, 'brightness_percent').getByRole('spinbutton').getAttribute('aria-invalid'), 'true');
    const workspace = await page.locator('.widget-layout-scroll').boundingBox();
    await drag(row(memory, 'brightness_percent').getByRole('button', { name: '拖动变量 brightness_percent' }), { x: workspace.x + workspace.width - 60, y: workspace.y + workspace.height - 60 });
    assert.equal(await page.locator('.widget').count(), 3, 'background splits into single card');
    assert.equal(await page.locator('.widget:not(.variable-list-card)').getByRole('spinbutton').evaluate(element => element === window.__qaInput), true, 'split keeps DOM input');
    assert.equal(await page.evaluate(() => window.__cardsQA.writes.length), 0, 'drag never writes');
    // Whole-card movement never merges its rows.
    const count = await cpu.locator('.variable-list-row').count();
    await drag(cpu.locator('.widget-header .widget-drag-handle'), await point(memory.locator('.widget-body'), .9, .5));
    assert.equal(await cpu.locator('.variable-list-row').count(), count);
    assert.equal(await page.locator('.widget').count(), 3);
    await cpu.locator('.widget-header').getByRole('button', { name: /^设置 / }).click();
    await page.getByRole('textbox', { name: '显示名称', exact: true }).fill('笔记本状态');
    await page.getByRole('button', { name: '完成', exact: true }).click();
    assert.equal(await cpu.locator('.widget-header strong').innerText(), '笔记本状态');
    await page.screenshot({ path: artifact('editing') });
    await page.evaluate(() => { window.__cardsQA.failSave = true });
    await page.getByRole('button', { name: '保存视图', exact: true }).click();
    await page.getByRole('alert').filter({ hasText: '模拟保存失败' }).waitFor();
    assert.equal(await page.locator('.widget-drag-handle').count() > 0, true, 'failed save keeps editing');
    await page.evaluate(() => { window.__cardsQA.failSave = false });
    await page.getByRole('button', { name: '保存视图', exact: true }).click();
    await page.getByRole('button', { name: '编辑视图', exact: true }).waitFor();
    assert.equal(await page.locator('.widget-drag-handle').count(), 0);
    assert.equal(await page.locator('.compact-card-resize').count(), 0);
    assert.equal(await page.getByRole('spinbutton').count(), 1, 'view mode keeps variable editor');
    assert.equal(await page.getByRole('spinbutton').isEnabled(), true);
    await page.screenshot({ path: artifact('viewing') });
    const saved = await page.evaluate(() => window.__cardsQA.saved());
    assert.equal(saved[0].widgets.find(widget => widget.id === 'cpu_percent').title, '笔记本状态');
    await page.getByRole('button', { name: '编辑视图', exact: true }).click();
    await page.getByRole('combobox', { name: '视图布局' }).click();
    await page.getByRole('option', { name: '铺满分栏', exact: true }).click();
    assert.equal(await page.getByRole('spinbutton').evaluate(element => element === window.__qaInput), true, 'layout switch keeps editor');
    await page.getByRole('button', { name: '取消', exact: true }).click();
    await page.getByRole('button', { name: '编辑视图', exact: true }).waitFor();
    await page.setViewportSize({ width: 850, height: 781 });
    await page.waitForTimeout(250);
    assert.ok(await page.locator('.widget').evaluateAll(cards => cards.every(card => card.getBoundingClientRect().right <= 850)), 'narrow cards fit viewport');
    await page.screenshot({ path: artifact('narrow') });
    await page.getByRole('button', { name: '新建视图', exact: true }).click();
    assert.equal(await page.getByRole('button', { name: '保存视图', exact: true }).count(), 1);
    await page.getByRole('button', { name: '取消', exact: true }).click();
    await page.getByRole('tab', { name: '视图', exact: true }).click();
    await page.locator('.view-row > button').filter({ hasText: '笔记本' }).click();
    assert.equal(await page.getByRole('button', { name: '编辑视图', exact: true }).count(), 1, 'reopening defaults to viewing');
    // Clean, screenshot-sized example matching the user's eight notebook variables.
    await page.setViewportSize({ width: 1264, height: 781 });
    await page.goto(`${process.env.QA_URL || 'http://127.0.0.1:62817'}/test/variable-cards.html`, { waitUntil: 'networkidle' });
    await drag(catalog('battery_percent'), await point(cpu.locator('.widget-body')));
    await drag(memory.getByRole('button', { name: '拖动变量 memory_percent', exact: true }), await point(cpu.locator('.variable-list-add')));
    await memory.getByRole('button', { name: '移除组件', exact: true }).click();
    for (const name of ['battery_charging', 'battery_on_ac']) await drag(catalog(name), await point(cpu.locator('.variable-list-add')));
    const space = await page.locator('.widget-layout-scroll').boundingBox();
    await drag(catalog('volume_percent'), { x: space.x + space.width - 50, y: space.y + space.height - 80 });
    const controls = page.locator('.widget').filter({ has: page.getByRole('heading', { name: 'volume_percent', exact: true }) });
    await drag(catalog('brightness_percent'), await point(controls.locator('.widget-body')));
    await drag(catalog('volume_muted'), await point(controls.locator('.variable-list-add')));
    for (const [card, title] of [[cpu, '笔记本状态'], [controls, '声音与显示']]) {
      await card.locator('.widget-header').getByRole('button', { name: /^设置 / }).click();
      await page.getByRole('textbox', { name: '显示名称', exact: true }).fill(title);
      await page.getByRole('button', { name: '完成', exact: true }).click();
    }
    const orderBeforeKeyboard = await cpu.locator('.variable-list-row .variable-title').allTextContents();
    await row(cpu, 'cpu_percent').getByRole('button', { name: '拖动变量 cpu_percent', exact: true }).focus();
    await page.keyboard.press('Space');
    await page.keyboard.press('ArrowDown'); await page.keyboard.press('ArrowDown');
    await page.keyboard.press('Space');
    await page.waitForTimeout(200);
    assert.notDeepEqual(await cpu.locator('.variable-list-row .variable-title').allTextContents(), orderBeforeKeyboard, 'keyboard drag reorders rows');
    await controls.locator('..').getByRole('button', { name: /卡片尺寸/ }).focus();
    await page.keyboard.press('ArrowRight');
    await page.getByRole('button', { name: '保存视图', exact: true }).click();
    await page.getByRole('button', { name: '编辑视图', exact: true }).waitFor();
    // Viewing mode still permits intentional variable writes (to the mock API).
    const volume = row(controls, 'volume_percent').getByRole('spinbutton');
    await volume.fill('80'); await volume.press('Enter');
    await page.waitForFunction(() => window.__cardsQA.writes.length === 1);
    await page.waitForTimeout(150);
    assert.equal(await controls.locator('.form-error').count(), 0);
    await page.getByRole('button', { name: '切换到深色主题' }).click();
    await page.waitForTimeout(250);
    await page.screenshot({ path: artifact('overview-dark') });
    assert.deepEqual(errors, []);
    console.log('PASS: mode transitions, valid/cancelled/invalid drops, merge/add/duplicate/reorder/move/split, stable draft DOM, card layout drag, rename, failed/successful save, cancel, narrow viewport, reopen.');
    console.log('Structural changes made zero writes; intentional viewing-mode operation verified with mock API only. No page errors. Screenshots:', artifact('{editing,viewing,narrow,overview-dark}'));
  } catch (error) {
    await page.screenshot({ path: artifact('failure') });
    console.error('Page errors:', errors);
    throw error;
  } finally { await browser.close(); }
})().catch(error => { console.error(error); process.exitCode = 1; });
